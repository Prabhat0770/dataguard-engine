import os
from datetime import datetime
from typing import Dict, Any
import pandas as pd

from .decorators import benchmark_and_log
from .profiler import DatasetProfiler


class DataHealthReporter:
    """Generates an automated, executive-ready Markdown data quality report."""

    def __init__(
        self,
        profiler: DatasetProfiler,
        cleaned_df: pd.DataFrame,
        report_dir: str = "reports"
    ):
        self.profiler = profiler
        self.cleaned_df = cleaned_df
        self.report_dir = report_dir
        self.initial_mem = self.profiler.memory_usage_mb
        self.final_mem = self.cleaned_df.memory_usage(deep=True).sum() / (1024 * 1024)
        self.mem_reduction = ((self.initial_mem - self.final_mem) / self.initial_mem) * 100.0

    @benchmark_and_log("Markdown Report Generation")
    def generate(self, filename: str = "data_health_report.md") -> str:
        os.makedirs(self.report_dir, exist_ok=True)
        report_path = os.path.join(self.report_dir, filename)
        now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

        # 1. Missing values extraction
        missing_audit = self.profiler.get_missing_summary()

        # 2. Vectorized Outlier Auditing on numerical columns
        outlier_rows = []
        for col in self.profiler.numerical_columns:
            outlier_info = self.profiler.detect_outliers_numpy(col, method="iqr")
            outlier_rows.append(
                f"| `{col}` | {outlier_info['outlier_count']} | {outlier_info['outlier_percentage']:.2f}% | "
                f"[{outlier_info['lower_bound']:.2f}, {outlier_info['upper_bound']:.2f}] |"
            )

        # 3. Missing values table rows
        missing_rows = []
        for col, meta in missing_audit.items():
            missing_rows.append(
                f"| `{col}` | `{meta['dtype']}` | {meta['null_count']} | {meta['null_percentage']:.2f}% |"
            )

        # 4. Compose Markdown Document
        markdown_content = f"""# 🛡️ DataGuard Quality & Profile Report
*Generated by DataGuard Engine v1.0 on `{now_str}`*

---

## 1. Executive Summary

| Metric | Raw Dataset | Cleaned Dataset | Delta / Optimization |
| :--- | :--- | :--- | :--- |
| **Total Rows** | {len(self.profiler)} | {len(self.cleaned_df)} | Exact Match (0 row loss) |
| **Total Columns** | {len(self.profiler.df.columns)} | {len(self.cleaned_df.columns)} | Preserved |
| **RAM Footprint** | {self.initial_mem:.3f} MB | {self.final_mem:.3f} MB | **{self.mem_reduction:.2f}% reduction** |
| **Missing Values** | {int(self.profiler.df.isnull().sum().sum())} | {int(self.cleaned_df.isnull().sum().sum())} | **100% resolved** |

---

## 2. Missing Value Audit

| Column Name | Ingested Data Type | Missing Count | Missing (%) |
| :--- | :--- | :--- | :--- |
{chr(10).join(missing_rows)}

---

## 3. Vectorized Outlier Audit (IQR Method)

| Target Column | Outlier Points | Contamination Rate | IQR Boundaries [Lower, Upper] |
| :--- | :--- | :--- | :--- |
{chr(10).join(outlier_rows)}

---

## 4. Applied Transformation Pipeline Steps
1. **`MissingValueImputer`**: Categorical columns imputed with mode; numerical columns imputed with median.
2. **`VectorizedOutlierCapper`**: Applied NumPy vectorized boundary clipping at `[Q1 - 1.5*IQR, Q3 + 1.5*IQR]`.
3. **`MemoryOptimizer`**: Downcasted `float64` to `float32`, `int64` to compact integer types, and converted low-cardinality string columns (`<20%` unique) to `category` dtypes.

---
*Report written to disk via DataGuard Engine context manager.*
"""
        with open(report_path, mode="w", encoding="utf-8") as f:
            f.write(markdown_content)

        return report_path